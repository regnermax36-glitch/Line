document.addEventListener('DOMContentLoaded', () => {
    const categoryNav = document.getElementById('categoryNav');
    const toolsContainer = document.getElementById('toolsContainer');
    const globalSearch = document.getElementById('globalSearch');
    const themeToggle = document.getElementById('themeToggle');
    const sunIcon = document.getElementById('sunIcon');
    const moonIcon = document.getElementById('moonIcon');
    const statsContainer = document.getElementById('statsContainer');
    const trendingContainer = document.getElementById('trendingContainer');
    const sponsorsContainer = document.getElementById('sponsorsContainer');
    const footerCategories = document.getElementById('footerCategories');

    // Theme Toggle
    themeToggle.addEventListener('click', () => {
        document.documentElement.classList.toggle('dark');
        const isDark = document.documentElement.classList.contains('dark');
        sunIcon.classList.toggle('hidden', !isDark);
        moonIcon.classList.toggle('hidden', isDark);
        localStorage.setItem('theme', isDark ? 'dark' : 'light');
    });

    // Load saved theme
    if (localStorage.getItem('theme') === 'dark' ||
        (!localStorage.getItem('theme') && window.matchMedia('(prefers-color-scheme: dark)').matches)) {
        document.documentElement.classList.add('dark');
        sunIcon.classList.remove('hidden');
        moonIcon.classList.add('hidden');
    }

    // Render Stats
    statsContainer.innerHTML = data.stats.map(stat => `
        <div class="p-4 bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-2xl shadow-sm">
            <div class="text-2xl font-black text-brand-600 dark:text-brand-400">${stat.value}</div>
            <div class="text-xs font-bold text-slate-400 uppercase tracking-wider">${stat.label}</div>
        </div>
    `).join('');

    // Render Trending
    trendingContainer.innerHTML = data.trending.map(tool => `
        <span class="px-3 py-1 bg-slate-100 dark:bg-slate-800 text-slate-700 dark:text-slate-300 text-xs font-bold rounded-lg border border-slate-200 dark:border-slate-700 hover:border-brand-500 transition-colors cursor-pointer">${tool}</span>
    `).join('');

    // Render Sponsors
    sponsorsContainer.innerHTML = data.sponsors.map(tool => `
        <span class="px-3 py-1 bg-brand-50 dark:bg-brand-900/20 text-brand-700 dark:text-brand-300 text-xs font-bold rounded-lg border border-brand-100 dark:border-brand-800 hover:border-brand-500 transition-colors cursor-pointer">${tool}</span>
    `).join('');

    // Render Footer Categories
    footerCategories.innerHTML = data.categories.map(cat => `
        <a href="#${cat.id}" class="hover:text-brand-600 transition-colors">${cat.name}</a>
    `).join('');

    function renderTools(filter = '') {
        categoryNav.innerHTML = '';
        toolsContainer.innerHTML = '';

        let hasResults = false;

        data.categories.forEach(category => {
            const filteredTools = category.tools.filter(t =>
                t.name.toLowerCase().includes(filter.toLowerCase())
            );

            if (filteredTools.length === 0 && filter !== '') return;
            hasResults = true;

            // Nav Link
            const navLink = document.createElement('a');
            navLink.href = `#${category.id}`;
            navLink.className = 'flex items-center px-4 py-2.5 text-sm font-bold rounded-xl text-slate-600 dark:text-slate-400 hover:bg-white dark:hover:bg-slate-900 hover:text-brand-600 hover:shadow-sm transition-all border border-transparent hover:border-slate-100 dark:hover:border-slate-800';
            navLink.innerHTML = `<span>${category.name}</span> <span class="ml-auto text-[10px] bg-slate-100 dark:bg-slate-800 px-1.5 py-0.5 rounded-md group-hover:bg-brand-50">${filteredTools.length}</span>`;
            categoryNav.appendChild(navLink);

            // Category Section
            const section = document.createElement('section');
            section.id = category.id;
            section.className = 'scroll-mt-24';

            section.innerHTML = `
                <div class="flex items-center gap-6 mb-10">
                    <h2 class="text-3xl font-black tracking-tight">${category.name}</h2>
                    <div class="h-px flex-1 bg-gradient-to-r from-slate-200 to-transparent dark:from-slate-800"></div>
                </div>
                <div class="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-6">
                    ${filteredTools.map(tool => `
                        <div onclick="window.open('${tool.url}', '_blank')" class="group p-6 bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-[2rem] hover:border-brand-500 dark:hover:border-brand-500 hover:shadow-2xl hover:shadow-brand-500/10 transition-all duration-500 cursor-pointer flex flex-col justify-between">
                            <div>
                                <div class="flex justify-between items-start mb-6">
                                    <div class="w-14 h-14 bg-slate-50 dark:bg-slate-800 rounded-2xl flex items-center justify-center group-hover:bg-brand-600 group-hover:text-white transition-all duration-500 transform group-hover:rotate-12 group-hover:scale-110 shadow-inner">
                                        <span class="font-black text-2xl">${tool.name[0]}</span>
                                    </div>
                                    ${tool.is_new ? '<span class="px-3 py-1 bg-brand-600 text-white text-[10px] font-black rounded-full uppercase tracking-widest shadow-lg shadow-brand-600/30">New</span>' : ''}
                                </div>
                                <h3 class="font-black text-xl group-hover:text-brand-600 transition-colors mb-3">${tool.name}</h3>
                                <p class="text-sm text-slate-500 dark:text-slate-400 leading-relaxed">${tool.description}</p>
                            </div>
                            <div class="mt-8 pt-6 border-t border-slate-50 dark:border-slate-800/50 flex items-center justify-between">
                                <a href="${tool.url}" target="_blank" rel="noopener noreferrer" class="text-[10px] font-black text-slate-400 uppercase tracking-[0.2em] group-hover:text-brand-600 transition-colors">Visit Website</a>
                                <div class="w-8 h-8 rounded-full bg-slate-50 dark:bg-slate-800 flex items-center justify-center group-hover:bg-brand-600 group-hover:text-white transition-all transform group-hover:translate-x-1">
                                    <svg class="w-4 h-4" xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="3" stroke-linecap="round" stroke-linejoin="round"><path d="M5 12h14m-7-7 7 7-7 7"/></svg>
                                </div>
                            </div>
                        </div>
                    `).join('')}
                </div>
            `;
            toolsContainer.appendChild(section);
        });

        if (!hasResults) {
            toolsContainer.innerHTML = `
                <div class="py-32 text-center bg-white dark:bg-slate-900 rounded-[3rem] border border-dashed border-slate-200 dark:border-slate-800">
                    <div class="inline-flex items-center justify-center w-20 h-20 rounded-full bg-slate-50 dark:bg-slate-800 mb-6">
                        <svg class="w-10 h-10 text-slate-300" xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" stroke="currentColor"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M21 21l-6-6m2-5a7 7 0 11-14 0 7 7 0 0114 0z" /></svg>
                    </div>
                    <h3 class="text-2xl font-black mb-2">No matching tools found</h3>
                    <p class="text-slate-500 dark:text-slate-400">Try searching for something else or browse categories.</p>
                </div>
            `;
        }
    }

    globalSearch.addEventListener('input', (e) => {
        const query = e.target.value;
        renderTools(query);

        // Show Forex section if searching for related terms
        const marketInsights = document.getElementById('marketInsights');
        const searchLower = query.toLowerCase();
        if (searchLower.includes('forex') || searchLower.includes('trading') || searchLower.includes('market')) {
            marketInsights.classList.remove('hidden');
        } else {
            marketInsights.classList.add('hidden');
        }
    });

    renderTools();

    // Smooth scroll for nav links
    document.addEventListener('click', (e) => {
        const link = e.target.closest('a');
        if (link && link.hash && link.hash.startsWith('#cat-')) {
            e.preventDefault();
            const target = document.querySelector(link.hash);
            if (target) {
                window.scrollTo({
                    top: target.offsetTop - 100,
                    behavior: 'smooth'
                });
            }
        }
    });
});
